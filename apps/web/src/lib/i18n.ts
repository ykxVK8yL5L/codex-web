type Dictionary = typeof dictionaries["zh-CN"];
type DotPrefix<T extends string, U extends string> = `${T}.${U}`;
type NestedKeys<T> = {
  [K in keyof T & string]: T[K] extends Record<string, unknown> ? DotPrefix<K, NestedKeys<T[K]>> : K;
}[keyof T & string];

export type TranslationKey = NestedKeys<Dictionary>;

export function translate(locale: Locale, key: TranslationKey) {
  const parts = key.split(".");
  let value: unknown = dictionaries[locale];
  for (const part of parts) {
    value = value && typeof value === "object" ? (value as Record<string, unknown>)[part] : undefined;
  }
  return typeof value === "string" ? value : key;
}
